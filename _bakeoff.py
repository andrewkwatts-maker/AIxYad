"""Model bake-off: cycle through local models, run TASK-001 with short budget,
record outcome. Each model gets a clean state and ~6 min."""
import subprocess, sqlite3, time, sys
from pathlib import Path

PROJ = Path('H:/Github/Calculator')
PROJ_DB = PROJ / '.automatica' / 'project.db'
GLOBAL_DB = Path.home() / '.automatica' / 'automatica.db'

# (provider_id, name, model_name)
MODELS = [
    (231, 'Llama3.1',       'llama3.1:latest'),
    (230, 'Mistral',        'mistral:latest'),
    (5,   'Gemma3-12b',     'gemma3:12b'),
    (3,   'DeepseekCoder',  'deepseek-coder:6.7b'),
    (2,   'Phi4',           'phi4:latest'),
]

PROVIDER_IDS = [m[0] for m in MODELS]

def reset_project():
    conn = sqlite3.connect(str(PROJ_DB))
    conn.execute("DELETE FROM sprint_tasks")
    conn.execute("DELETE FROM sprints")
    conn.execute("DELETE FROM tasks WHERE display_id != 'TASK-001'")
    conn.execute(
        "UPDATE tasks SET failure_count=0, status='backlog', complexity=3, "
        "manual_claim_until=NULL, reserved_by='', reserved_at=NULL, "
        "started_at=NULL, completed_at=NULL"
    )
    conn.commit()
    conn.close()

def clear_calculator_files():
    """Wipe any files generated by previous runs (keep README, CLAUDE.md, .automatica, all logs)."""
    for p in PROJ.iterdir():
        # Preserve all log files, dotfiles/dotdirs, and the README/CLAUDE
        if p.name in {'README.md', 'CLAUDE.md'}:
            continue
        if p.name.startswith('.') or p.name.startswith('_'):
            continue
        if p.suffix == '.log':
            continue
        if p.is_file():
            p.unlink()
        elif p.is_dir():
            import shutil
            shutil.rmtree(p)

def set_active_provider(provider_id):
    conn = sqlite3.connect(str(GLOBAL_DB))
    for pid in PROVIDER_IDS:
        conn.execute("UPDATE providers SET enabled = ? WHERE id = ?",
                     (1 if pid == provider_id else 0, pid))
    conn.commit()
    conn.close()

def run_model(provider_name, log_path, minutes=6):
    cmd = [
        sys.executable, '-u', 'run_autonomous.py',
        '--Project', str(PROJ),
        '--provider', provider_name,
        '--max-minutes', str(minutes),
        '--max-sprints', '1',
        '--max-points', '5',
        '--max-iterations', '6',
        '--no-replenish',
    ]
    with open(log_path, 'w', encoding='utf-8') as f:
        r = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT,
                           cwd=str(Path(__file__).parent), timeout=minutes*60+60)
    return r.returncode

def analyse_log(log_path):
    text = log_path.read_text(encoding='utf-8', errors='replace') if log_path.exists() else ''
    lines = text.splitlines()
    done = sum(1 for ln in lines if 'TASK-001 DONE' in ln or '[TASK] DONE: TASK-001' in ln)
    failed = sum(1 for ln in lines if 'TASK-001 FAILED' in ln)
    parse_fail = sum(1 for ln in lines if 'JSON parse fail' in ln)
    iters_match = [ln for ln in lines if 'TASK-001 in' in ln and ('iterations' in ln)]
    file_writes = sum(1 for ln in lines if 'wrote' in ln.lower() and '.py' in ln)
    return {
        'done': done,
        'failed': failed,
        'parse_failures': parse_fail,
        'final_status_line': iters_match[-1] if iters_match else '',
        'file_writes_in_log': file_writes,
    }

def list_generated_files():
    keep = {'README.md', 'CLAUDE.md', '_run.log'}
    files = []
    for p in PROJ.rglob('*'):
        if p.is_file() and not any(part.startswith('.') for part in p.relative_to(PROJ).parts):
            rel = p.relative_to(PROJ)
            if rel.name not in keep:
                files.append(str(rel).replace('\\', '/'))
    return sorted(files)

def main():
    results = []
    print('=== Model Bake-off — TASK-001 (create main.py + requirements.txt) ===\n')
    for pid, name, model in MODELS:
        log_path = PROJ / f'_bake_{name}.log'
        print(f'[{name}] starting (model={model}, 6min budget)...')
        reset_project()
        clear_calculator_files()
        set_active_provider(pid)
        t0 = time.time()
        try:
            rc = run_model(name, log_path, minutes=6)
        except subprocess.TimeoutExpired:
            rc = -1
            print(f'  TIMEOUT')
        elapsed = time.time() - t0
        analysis = analyse_log(log_path)
        files = list_generated_files()
        result = {
            'name': name, 'model': model, 'returncode': rc,
            'elapsed_s': round(elapsed, 1), 'files_after': files,
            **analysis,
        }
        results.append(result)
        print(f'  ?? {analysis["final_status_line"] or "no terminal status"}')
        print(f'     parse_failures={analysis["parse_failures"]} files_after={files}\n')

    print('\n=== SUMMARY ===')
    for r in results:
        verdict = ('OK ' if r['done'] else ('FAIL' if r['failed'] else '????'))
        print(f'  [{verdict}] {r["name"]:14s} t={r["elapsed_s"]}s  parse_fails={r["parse_failures"]:3d}  '
              f'files={len(r["files_after"])}  {r["final_status_line"]}')
    print()
    return results

if __name__ == '__main__':
    main()
